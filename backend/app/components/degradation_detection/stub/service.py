"""Synthetic C2 output with planted ground truth (plan T-03).

Until C1 and C2 deliver real packages, this is the dataset C3 is developed and demonstrated on.
It is a development fixture, not evidence: results on it show that the pipeline finds what was
planted, nothing more.
"""

import json
from typing import Any

import yaml

from app.components.degradation_detection.stub.models import (
    DEFAULT_SEED,
    GROUND_TRUTH_FILE,
    GroundTruth,
    StubOutput,
)
from app.components.degradation_detection.stub.scenario import (
    HOTFIX_ID,
    build_ground_truth,
    build_packages,
    file_name,
)
from app.components.degradation_detection.stub.series import build_series
from app.domain.release_package import ReleasePackageV1

GROUND_TRUTH_HEADER = (
    "# Ground truth of the synthetic system. Generated by `c3 stub generate`; do not edit.\n"
    "# How to score events against it: see GroundTruth in\n"
    "# app/components/degradation_detection/stub/models.py\n"
)


def _json(payload: Any) -> str:
    return json.dumps(payload, indent=2, ensure_ascii=False) + "\n"


def _yaml(truth: GroundTruth) -> str:
    body = yaml.safe_dump(truth.model_dump(mode="json"), sort_keys=False, allow_unicode=True)
    return GROUND_TRUTH_HEADER + body


class StubService:
    def generate(self, seed: int = DEFAULT_SEED) -> StubOutput:
        """Build every file of the synthetic system as text. The same seed gives the same bytes."""
        packages = build_packages(seed)
        for name, payload in packages.items():
            if name != file_name(HOTFIX_ID):  # the hotfix is invalid on purpose
                ReleasePackageV1.model_validate(payload)
        truth = build_ground_truth(seed)

        system_files = {name: _json(payload) for name, payload in packages.items()}
        system_files[GROUND_TRUTH_FILE] = _yaml(truth)
        series_files = {
            f"{series.name}.json": _json(series.model_dump(mode="json"))
            for series in build_series(seed)
        }
        return StubOutput(
            seed=seed, system_files=system_files, series_files=series_files, ground_truth=truth
        )
